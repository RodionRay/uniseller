export function matchAssistantFaq(question:string):string|null{
  const q=question.trim().toLowerCase();
  if(!q)return null;
  for(const [pattern,answer] of ASSISTANT_FAQ){
    if(new RegExp(pattern,'i').test(q))return answer;
  }
  return null;
}

export function fallbackAssistantReply(question:string):string{
  const hit=matchAssistantFaq(question);
  if(hit)return hit;
  return [
    'Я помогаю разобраться с Uniseller: маркетплейсы, остатки, МойСклад/1С, цены и отзывы.',
    'Сформулируйте вопрос конкретнее — например про синхронизацию остатков или подключение кабинета.',
    `Также можно открыть ${PRODUCT_SITE}.`,
  ].join(' ');
}
